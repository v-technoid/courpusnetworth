# -*- coding: utf-8 -*-
"""Render country guides (tools/guides_data.py) to HTML.

The same HTML is used twice: embedded in js/guides.js so the app pages
(insurance.html, schemes.html, scholarships.html) can show the person's
own country, and written as static pages under /us/, /uk/ ... so search
engines can read them without running any script."""
import html, json

esc = lambda s: html.escape(str(s), quote=True)
def nm(P): return ('the ' + P['name']) if P['code'] in ('US', 'UK', 'AE') else P['name']
def sh(P): return ('the ' + P['short']) if P['code'] in ('US', 'UK', 'AE') else P['short']
EXT = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M14 4h6v6M20 4l-9 9M19 14v5a1 1 0 0 1-1 1H5a1 1 0 0 1-1-1V6a1 1 0 0 1 1-1h5"/></svg>'

def link(url, label='Official site'):
    return f'<a class="gd-link" href="{esc(url)}" target="_blank" rel="noopener">{label}{EXT}</a>'

def checked_note(P, checked):
    when = f'Checked {esc(checked)}.' if checked and checked != 'pending' else 'Being checked against official sources.'
    return (f'<p class="hint gd-checked">{when} Rules and amounts change, so confirm on the official page before you rely on a figure. '
            f'<a href="privacy.html#pp-{P["code"].lower()}">Who to check with in {esc(nm(P))}</a>.</p>')

def insurance_html(P, G, checked, with_calc_placeholder=True):
    I = G['insurance']
    pub = ''.join(f'<div class="gd-item"><h3>{esc(x["name"])}</h3><p>{esc(x["what"])}</p>{link(x["url"])}</div>' for x in I['public'])
    types = ''.join(f'''<article class="card gd-type"><h2>{esc(t["label"])}</h2><p>{esc(t["what"])}</p>
      <div class="grid-2 gd-pc"><div><h3 class="gd-pros">Pros</h3><ul>{''.join(f"<li>{esc(p)}</li>" for p in t["pros"])}</ul></div>
      <div><h3 class="gd-cons">Cons</h3><ul>{''.join(f"<li>{esc(c)}</li>" for c in t["cons"])}</ul></div></div></article>''' for t in I['types'])
    calc = '<div id="worldCalc"></div>' if with_calc_placeholder else ''
    return f'''<div class="card gd-intro"><h2>How Cover Works in {esc(nm(P))}</h2><p>{esc(I["intro"])}</p>
      <h3 class="gd-sub">What You Already Have</h3><div class="gd-grid">{pub}</div>
      <div class="callout gd-health"><div><strong>Health cover</strong><br>{esc(I["health"])}</div></div></div>
    {calc}
    <h2 class="gd-h">Types of Insurance, Pros and Cons</h2>
    <div class="gd-types">{types}</div>
    {checked_note(P, checked)}'''

def schemes_html(P, G, checked):
    out = ''
    for grp in G['schemes']:
        items = ''.join(f'<div class="gd-item"><h3>{esc(x["name"])}</h3><p>{esc(x["what"])}</p>{link(x["url"])}</div>' for x in grp['items'])
        out += f'<section class="card"><h2>{esc(grp["group"])}</h2><div class="gd-grid">{items}</div></section>'
    return out + checked_note(P, checked)

CATS = [('start', 'Start Here'), ('grant', 'Grants and Bursaries'), ('merit', 'Merit Awards'), ('loan', 'Loans'), ('work', 'Work While You Study'), ('saving', 'Saving for Study'), ('search', 'Find More')]
def students_html(P, G, checked):
    S = G['students']; out = f'<div class="card gd-intro"><p style="margin:0">{esc(S["intro"])}</p></div>'
    for key, label in CATS:
        items = [x for x in S['items'] if x['cat'] == key]
        if not items: continue
        cards = ''.join(f'<div class="gd-item"><h3>{esc(x["name"])}</h3><span class="pill gd-level">{esc(x["level"])}</span><p>{esc(x["what"])}</p>{link(x["url"])}</div>' for x in items)
        out += f'<section class="card"><h2>{label}</h2><div class="gd-grid">{cards}</div></section>'
    return out + checked_note(P, checked)

def js_payload(GUIDES, CDATA, checked):
    data = {}
    for c, G in GUIDES.items():
        P = CDATA[c]; I = G['insurance']
        data[c] = dict(insurance=insurance_html(P, G, checked), schemes=schemes_html(P, G, checked), students=students_html(P, G, checked),
                       calc=dict(disability=I['disability'], disabilityNote=I['disabilityNote'], lifeNote=I['lifeNote'], health=I['health']))
    return ('/* Generated by tools/build.py from tools/guides_data.py. Do not edit by hand. */\n'
            'window.CORPUS_GUIDES = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
            f'window.CORPUS_GUIDES_CHECKED = {json.dumps(checked)};\n')

PAGES = [
    ('insurance', 'insurance.html', 'Insurance', lambda P: f'Insurance in {nm(P)}: What You Have and What to Add',
     lambda P: f'Public cover in {sh(P)}, how much life and income cover fits you, and plain pros and cons of each type of insurance. Private, free calculator.'),
    ('schemes', 'benefits.html', 'Government Schemes', lambda P: f'Government Schemes and Benefits in {nm(P)}',
     lambda P: f'Savings incentives, family payments, pensions and home buying help in {sh(P)}, each with a link to the official page.'),
    ('students', 'student-aid.html', 'Student Aid', lambda P: f'Student Aid and Scholarships in {nm(P)}',
     lambda P: f'Grants, loans, savings schemes and scholarship searches for students in {sh(P)}, from official sources.'),
]
